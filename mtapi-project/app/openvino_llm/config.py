_CONFIG_LOCK = threading.RLock()


class ModelCapabilities(BaseModel):
    model_config = ConfigDict(extra="allow")

    streaming: bool = True
    tools: bool = True
    reasoning: bool = True
    vision: bool = False
    prompt_cache: bool = True


class ModelEntry(BaseModel):
    model_config = ConfigDict(extra="allow")

    id: str = DEFAULT_MODEL_ID
    model_path: str = DEFAULT_MODEL_PATH
    context_window: int = 40960
    max_tokens: int = 4096
    max_tokens_default: int = 1024
    enable_thinking_default: bool = False
    temperature_default: float | None = 0.7
    top_p_default: float | None = 0.95
    top_k_default: int | None = None
    repetition_penalty_default: float | None = None
    runtime_profiles: dict[str, dict[str, Any]] = Field(default_factory=dict)
    tool_parser: str = "hermes3"
    capabilities: ModelCapabilities = Field(default_factory=ModelCapabilities)


class RuntimeConfig(BaseModel):
    model_config = ConfigDict(extra="allow")

    model_path: str = DEFAULT_MODEL_PATH
    cache_dir: str = DEFAULT_CACHE_DIR
    device: str = "GPU"
    kv_cache_precision: str = "u4"
    preflight_min_mb: int = 8192
    auto_load_on_start: bool = False
    auto_load_on_request: bool = True
    enable_sse_keepalive: bool = True
    sse_keepalive_interval_s: float = 5.0
    runtime_overlay_path: str = DEFAULT_OVERLAY_PATH
    engine: str = "playground"
    preflight_policy: str = "playground"
    ovms_rest_workers: int = 4
    ovms_cache_size_gb: int = 0
    ovms_max_num_seqs: int = 256
    ovms_max_num_batched_tokens: int = 0
    ovms_enable_prefix_caching: bool = True
    ovms_dynamic_split_fuse: bool = True
    ovms_reasoning_parser: str = "qwen3"


class CageConfig(BaseModel):
    model_config = ConfigDict(extra="allow")

    backend: str = "auto"  # "auto" | "systemd_scope" | "cgroup_prlimit" | "none"
    memory_max: str = "9G"
    memory_high: str = "8G"
    memory_swap_max: str = "0"
    oom_score_adjust: int = 1000
    rss_cap_mb: int = 11500
    watchdog_floor_enabled: bool = False
    watchdog_min_mb: int = 192


class OpenVinoSettings(BaseModel):
    model_config = ConfigDict(extra="allow")

    host: str = DEFAULT_HOST
    port: int = DEFAULT_PORT
    api_key: str = DEFAULT_API_KEY
    enforce_api_key: bool = False
    timeout_ms: int = DEFAULT_TIMEOUT_MS
    active_model_id: str = DEFAULT_MODEL_ID
    models: list[ModelEntry] = Field(
        default_factory=lambda: [ModelEntry()]
    )
    runtime: RuntimeConfig = Field(default_factory=RuntimeConfig)
    cage: CageConfig = Field(default_factory=CageConfig)

    @property
    def base_url(self) -> str:
        return f"http://{self.host}:{self.port}/v1"

    @property
    def model_source_url(self) -> str:
        return f"http://{self.host}:{self.port}/v1/models"

    def active_model(self) -> ModelEntry:
        for m in self.models:
            if m.id == self.active_model_id:
                return m
        if self.models:
            return self.models[0]
        return ModelEntry(
            id=self.active_model_id or DEFAULT_MODEL_ID,
            model_path=self.runtime.model_path or DEFAULT_MODEL_PATH,
        )

    def find_model(self, model_id: str | None) -> ModelEntry:
        if model_id:
            for m in self.models:
                if m.id == model_id:
                    return m
        return self.active_model()


def settings_path() -> Path:
    env_override = os.environ.get("MTAPI_OPENVINO_SETTINGS")
    if env_override:
        return Path(env_override).expanduser().resolve()
    return DATA_DIR / "settings.json"


def config_env_path() -> Path:
    return settings_path().parent / "config.env"


def _write_config_env(cfg: OpenVinoSettings) -> None:
    active = cfg.active_model()
    env_file = config_env_path()
    env_file.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Auto-generated by ffTransmute WebUI (OpenVINO tab)",
        f"VINO_HOST={cfg.host}",
        f"VINO_PORT={cfg.port}",
        f"VINO_MODEL_ID={active.id}",
        f"VINO_MODEL_PATH={active.model_path or cfg.runtime.model_path}",
        f"VINO_CACHE_DIR={cfg.runtime.cache_dir}",
        f"VINO_DEVICE={cfg.runtime.device}",
        f"VINO_KV_CACHE_PRECISION={cfg.runtime.kv_cache_precision}",
        f"VINO_PREFLIGHT_MB={cfg.runtime.preflight_min_mb}",
        f"VINO_PREFLIGHT_POLICY={cfg.runtime.preflight_policy}",
        f"VINO_ENGINE={cfg.runtime.engine}",
        f"VINO_TOOL_PARSER={active.tool_parser}",
        f"VINO_TIMEOUT_MS={cfg.timeout_ms}",
        f"VINO_CONTEXT_WINDOW={active.context_window}",
        f"VINO_MAX_TOKENS={active.max_tokens}",
        f"VINO_MAX_TOKENS_DEFAULT={active.max_tokens_default}",
        f"VINO_ENABLE_THINKING={'true' if active.enable_thinking_default else 'false'}",
        f"VINO_MEMORY_MAX={cfg.cage.memory_max}",
        f"VINO_MEMORY_HIGH={cfg.cage.memory_high}",
        f"VINO_MEMORY_SWAP_MAX={cfg.cage.memory_swap_max}",
        f"VINO_OOM_SCORE_ADJUST={cfg.cage.oom_score_adjust}",
        f"VINO_RSS_CAP_MB={cfg.cage.rss_cap_mb}",
        f"VINO_WATCHDOG_FLOOR={'on' if cfg.cage.watchdog_floor_enabled else 'off'}",
        "",
    ]
    tmp = env_file.with_suffix(".env.tmp")
    tmp.write_text("\n".join(lines), encoding="utf-8")
    tmp.replace(env_file)


def load_config() -> OpenVinoSettings:
    with _CONFIG_LOCK:
        path = settings_path()
        if not path.is_file():
            cfg = OpenVinoSettings()
            from .profiles import RUNTIME_KEYS
            for entry in cfg.models:
                entry.runtime_profiles[cfg.runtime.engine] = {k: getattr(cfg.runtime, k) for k in RUNTIME_KEYS}
            try:
                save_config(cfg)
            except OSError:
                pass
            return cfg
        try:
            raw = json.loads(path.read_text(encoding="utf-8"))
            if isinstance(raw, dict):
                cfg = OpenVinoSettings.model_validate(raw)
                # In-memory migration preserves the existing global tuning for every model.
                from .profiles import RUNTIME_KEYS, effective_runtime
                for entry in cfg.models:
                    entry.runtime_profiles.setdefault(cfg.runtime.engine, {k: getattr(cfg.runtime, k) for k in RUNTIME_KEYS})
                cfg.runtime = effective_runtime(cfg, cfg.active_model())
                return cfg
        except Exception:
            pass
        return OpenVinoSettings()


def save_config(cfg: OpenVinoSettings) -> OpenVinoSettings:
    with _CONFIG_LOCK:
        path = settings_path()
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_suffix(".json.tmp")
        payload = cfg.model_dump(mode="json")
        tmp.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
        tmp.replace(path)
        try:
            _write_config_env(cfg)
        except OSError:
            pass
        return cfg


def validate_and_merge_config(
    raw: dict[str, Any],
    base: OpenVinoSettings | None = None,
) -> OpenVinoSettings:
    """Validate incoming partial or full settings dict; raise ValueError with a
    clean human-readable message on invalid values (routes return 200 + ok:false).
    """
    if not isinstance(raw, dict):
        raise ValueError("Configuration body must be a JSON object")

    current = (base or load_config()).model_dump(mode="json")

    # Top-level scalar fields
    if "host" in raw:
        host = str(raw["host"] or "").strip()
        if not host:
            raise ValueError("Host must not be empty")
        current["host"] = host

    if "port" in raw:
        try:
            port = int(raw["port"])
        except (TypeError, ValueError) as exc:
            raise ValueError(f"Port must be an integer (got {raw['port']!r})") from exc
        if not (1024 <= port <= 65535):
            raise ValueError(f"Port must be between 1024 and 65535 (got {port})")
        current["port"] = port

    if "api_key" in raw:
        current["api_key"] = str(raw["api_key"] if raw["api_key"] is not None else "").strip()

    if "enforce_api_key" in raw:
        current["enforce_api_key"] = bool(raw["enforce_api_key"])

    if "timeout_ms" in raw:
        try:
            timeout_ms = int(raw["timeout_ms"])
        except (TypeError, ValueError) as exc:
            raise ValueError(f"Timeout (ms) must be an integer (got {raw['timeout_ms']!r})") from exc
        if timeout_ms < 1000 or timeout_ms > 3600000:
            raise ValueError("Timeout (ms) must be between 1000 and 3600000")
        current["timeout_ms"] = timeout_ms

    # Runtime sub-object (or flat convenience keys)
    rt = dict(current.get("runtime") or {})
    raw_rt = raw.get("runtime") if isinstance(raw.get("runtime"), dict) else {}
    for k in (
        "model_path",
        "cache_dir",
        "device",
        "kv_cache_precision",
        "preflight_min_mb",
        "auto_load_on_start",
        "auto_load_on_request",
        "enable_sse_keepalive",
        "sse_keepalive_interval_s",
        "runtime_overlay_path",
        "engine", "preflight_policy", "ovms_rest_workers", "ovms_cache_size_gb",
        "ovms_max_num_seqs", "ovms_max_num_batched_tokens",
        "ovms_enable_prefix_caching", "ovms_dynamic_split_fuse", "ovms_reasoning_parser",
    ):
        if k in raw_rt:
            rt[k] = raw_rt[k]
        elif k in raw:
            rt[k] = raw[k]

    rt["model_path"] = str(rt.get("model_path") or DEFAULT_MODEL_PATH).strip()
    rt["cache_dir"] = str(rt.get("cache_dir") or DEFAULT_CACHE_DIR).strip()
    rt["device"] = str(rt.get("device") or "GPU").strip().upper()
    if rt["device"] not in {"GPU", "CPU", "NPU", "AUTO"} and not rt["device"].startswith("GPU."):
        raise ValueError(f"Unsupported OpenVINO device: {rt['device']!r} (expected GPU, CPU, NPU, or AUTO)")

    kv_prec = str(rt.get("kv_cache_precision") or "u4").strip().lower()
    if kv_prec not in {"u4", "u8", "f16", "auto"}:
        raise ValueError(f"Unsupported KV cache precision: {kv_prec!r} (expected u4, u8, f16, or auto)")
    rt["kv_cache_precision"] = kv_prec

    try:
        preflight = int(rt.get("preflight_min_mb", 8192))
    except (TypeError, ValueError) as exc:
        raise ValueError("Preflight Min MB must be an integer") from exc
    if preflight < 256 or preflight > 65536:
        raise ValueError("Preflight Min MB must be between 256 and 65536")
    rt["preflight_min_mb"] = preflight
    if rt.get("engine", "playground") not in {"playground", "genai"}:
        raise ValueError("Engine must be playground or genai")
    if rt.get("preflight_policy", "playground") not in {"playground", "fixed"}:
        raise ValueError("Preflight policy must be playground or fixed")
    for key, minimum, maximum, default in (
        ("ovms_rest_workers", 1, 64, 4), ("ovms_cache_size_gb", 0, 64, 0),
        ("ovms_max_num_seqs", 1, 4096, 256), ("ovms_max_num_batched_tokens", 0, 2097152, 0),
    ):
        try:
            value = int(rt.get(key, default))
        except (ValueError, TypeError) as exc:
            raise ValueError(f"{key} must be an integer") from exc
        if not minimum <= value <= maximum:
            raise ValueError(f"{key} must be between {minimum} and {maximum}")
        rt[key] = value
    rt["auto_load_on_start"] = bool(rt.get("auto_load_on_start", False))
    rt["auto_load_on_request"] = bool(rt.get("auto_load_on_request", True))
    rt["enable_sse_keepalive"] = bool(rt.get("enable_sse_keepalive", True))
    try:
        rt["sse_keepalive_interval_s"] = max(1.0, float(rt.get("sse_keepalive_interval_s", 5.0)))
    except (TypeError, ValueError):
        rt["sse_keepalive_interval_s"] = 5.0
    rt["runtime_overlay_path"] = str(rt.get("runtime_overlay_path") or "").strip()
    current["runtime"] = rt

    # Cage sub-object (or flat convenience keys)
    cage = dict(current.get("cage") or {})
    raw_cage = raw.get("cage") if isinstance(raw.get("cage"), dict) else {}
    for k in (
        "backend",
        "memory_max",
        "memory_high",
        "memory_swap_max",
        "oom_score_adjust",
        "rss_cap_mb",
        "watchdog_floor_enabled",
        "watchdog_min_mb",
    ):
        if k in raw_cage:
            cage[k] = raw_cage[k]
        elif k in raw:
            cage[k] = raw[k]

    backend = str(cage.get("backend") or "auto").strip().lower()
    if backend not in {"auto", "systemd_scope", "cgroup_prlimit", "none"}:
        raise ValueError(f"Unsupported cage backend: {backend!r}")
    cage["backend"] = backend

    for mem_key, label in (
        ("memory_max", "MemoryMax"),
        ("memory_high", "MemoryHigh"),
        ("memory_swap_max", "MemorySwapMax"),
    ):
        val = str(cage.get(mem_key, "")).strip()
        if not val:
            raise ValueError(f"{label} must not be empty")
        cage[mem_key] = val

    try:
        oom = int(cage.get("oom_score_adjust", 1000))
    except (TypeError, ValueError) as exc:
        raise ValueError("OOMScoreAdjust must be an integer") from exc
    if not (-1000 <= oom <= 1000):
        raise ValueError("OOMScoreAdjust must be between -1000 and 1000")
    cage["oom_score_adjust"] = oom

    try:
        rss_cap = int(cage.get("rss_cap_mb", 11500))
    except (TypeError, ValueError) as exc:
        raise ValueError("RSS Cap MB must be an integer") from exc
    if rss_cap < 512 or rss_cap > 131072:
        raise ValueError("RSS Cap MB must be between 512 and 131072")
    cage["rss_cap_mb"] = rss_cap
    cage["watchdog_floor_enabled"] = bool(cage.get("watchdog_floor_enabled", False))
    try:
        cage["watchdog_min_mb"] = max(32, int(cage.get("watchdog_min_mb", 192)))
    except (TypeError, ValueError):
        cage["watchdog_min_mb"] = 192
    current["cage"] = cage

    # Models list
    if "models" in raw:
        raw_models = raw["models"]
        if not isinstance(raw_models, list) or not raw_models:
            raise ValueError("Models list must be a non-empty array")
        parsed_models: list[dict[str, Any]] = []
        seen_ids: set[str] = set()
        for item in raw_models:
            if isinstance(item, str):
                m_id = item.strip()
                item_dict: dict[str, Any] = {"id": m_id}
            elif isinstance(item, dict):
                m_id = str(item.get("id") or "").strip()
                item_dict = dict(item)
                item_dict["id"] = m_id
            else:
                raise ValueError("Each model entry must be an object or string ID")
            if not m_id:
                raise ValueError("Model ID must not be empty")
            if m_id in seen_ids:
                continue
            seen_ids.add(m_id)
            # Merge with existing model entry if present
            existing = next(
                (m for m in (current.get("models") or []) if isinstance(m, dict) and m.get("id") == m_id),
                {},
            )
            merged_m = {
                "id": m_id,
                "model_path": rt["model_path"],
                "context_window": 40960,
                "max_tokens": 4096,
                "max_tokens_default": 1024,
                "enable_thinking_default": False,
                "temperature_default": 0.7,
                "top_p_default": 0.95,
                "capabilities": {
                    "streaming": True,
                    "tools": True,
                    "reasoning": True,
                    "vision": False,
                    "prompt_cache": True,
                },
                **existing,
                **item_dict,
            }
            parsed_models.append(merged_m)
        if not parsed_models:
            raise ValueError("Models list must contain at least one valid model ID")
        current["models"] = parsed_models

    if "active_model_id" in raw:
        active_id = str(raw["active_model_id"] or "").strip()
        if active_id:
            current["active_model_id"] = active_id

    # Ensure active_model_id is in models list
    model_ids = [m["id"] for m in current["models"]]
    if current.get("active_model_id") not in model_ids:
        current["active_model_id"] = model_ids[0]

    # Apply convenience active-model overrides if passed at top level
    active_idx = next(
        (i for i, m in enumerate(current["models"]) if m["id"] == current["active_model_id"]),
        0,
    )
    active_entry = dict(current["models"][active_idx])
    if "context_window" in raw:
        try:
            cw = int(raw["context_window"])
        except (TypeError, ValueError) as exc:
            raise ValueError("contextWindow must be an integer") from exc
        if cw < 512 or cw > 2097152:
            raise ValueError("contextWindow must be between 512 and 2097152")
        active_entry["context_window"] = cw

    if "max_tokens" in raw:
        try:
            mt = int(raw["max_tokens"])
        except (TypeError, ValueError) as exc:
            raise ValueError("maxTokens must be an integer") from exc
        if mt < 1 or mt > 2097152:
            raise ValueError("maxTokens must be between 1 and 2097152")
        active_entry["max_tokens"] = mt

    if "max_tokens_default" in raw:
        try:
            mtd = int(raw["max_tokens_default"])
        except (TypeError, ValueError) as exc:
            raise ValueError("Default max_tokens must be an integer") from exc
        if mtd < 1 or mtd > 2097152:
            raise ValueError("Default max_tokens must be between 1 and 2097152")
        active_entry["max_tokens_default"] = mtd

    if "enable_thinking_default" in raw:
        active_entry["enable_thinking_default"] = bool(raw["enable_thinking_default"])

    for key in ('temperature_default', 'top_p_default', 'top_k_default', 'repetition_penalty_default'):
        if key in raw:
            active_entry[key] = raw[key]

    if "capabilities" in raw and isinstance(raw["capabilities"], dict):
        caps = dict(active_entry.get("capabilities") or {})
        for ck in ("streaming", "tools", "reasoning", "vision", "prompt_cache"):
            if ck in raw["capabilities"]:
                caps[ck] = bool(raw["capabilities"][ck])
        active_entry["capabilities"] = caps

    if "model_path" in raw or "model_path" in raw_rt:
        active_entry["model_path"] = rt["model_path"]
    elif active_entry.get("model_path"):
        rt["model_path"] = active_entry["model_path"]

    current["models"][active_idx] = active_entry
    cfg = OpenVinoSettings.model_validate(current)
    from .profiles import RUNTIME_KEYS, effective_runtime, describe, validate_profile
    engine = cfg.runtime.engine
    active = cfg.active_model()
    if raw.get('active_model_id') and 'runtime' not in raw and not any(k in raw for k in RUNTIME_KEYS):
        cfg.runtime = effective_runtime(cfg, active)
    # The active form is the source of truth for this engine's model runtime profile.
    active.runtime_profiles[engine] = {k: getattr(cfg.runtime, k) for k in RUNTIME_KEYS}
    for entry in cfg.models:
        profile = entry.runtime_profiles.setdefault(engine, {k: getattr(cfg.runtime, k) for k in RUNTIME_KEYS})
        descriptor = describe(entry, engine, profile.get('device', cfg.runtime.device))
        values = {k: getattr(entry, k) for k in descriptor['generation_keys']}
        values['runtime'] = {k: v for k, v in profile.items() if k in descriptor['runtime_keys']}
        validate_profile(values, descriptor)
        entry.capabilities = ModelCapabilities.model_validate(descriptor['capabilities'])
        if not descriptor['thinking_toggle']:
            entry.enable_thinking_default = False
    return cfg


def build_v1_model_card(
    entry: ModelEntry,
    cfg: OpenVinoSettings,
    loaded_model_id: str | None = None,
    created_ts: int | None = None,
) -> dict[str, Any]:
    """Build a single OpenAI /v1/models descriptor with all Cline/OpenRouter/vLLM
    context-window, max-token, timeout, and capability keys.
    """
    ts = created_ts if created_ts is not None else int(time.time())
    caps = entry.capabilities
    is_hot = bool(loaded_model_id and loaded_model_id == entry.id)
    return {
        "id": entry.id,
        "object": "model",
        "created": ts,
        "owned_by": "openvino",
        "root": entry.id,
        "parent": None,
        # Context window keys inspected by Cline, OpenRouter, LiteLLM, LM Studio, vLLM
        "context_length": entry.context_window,
        "contextWindow": entry.context_window,
        "max_model_len": entry.context_window,
        "max_context_length": entry.context_window,
        # Output token limits inspected by Cline & OpenAI-compatible clients
        "max_tokens": entry.max_tokens,
        "maxTokens": entry.max_tokens,
        "max_completion_tokens": entry.max_tokens,
        "max_output_tokens": entry.max_tokens,
        "default_max_tokens": entry.max_tokens_default,
        # Timeout (ms) to prevent 30s iGPU prefill cutoff
        "timeout": cfg.timeout_ms,
        "timeout_ms": cfg.timeout_ms,
        # Capabilities object
        "capabilities": {
            "streaming": caps.streaming,
            "tools": caps.tools,
            "reasoning": caps.reasoning,
            "vision": caps.vision,
            "prompt_cache": caps.prompt_cache,
            "function_calling": caps.tools,
        },
        # Cline / LiteLLM model_info block
        "model_info": {
            "context_window": entry.context_window,
            "max_tokens": entry.max_tokens,
            "max_input_tokens": entry.context_window,
            "max_output_tokens": entry.max_tokens,
            "supports_streaming": caps.streaming,
            "supports_tools": caps.tools,
            "supports_function_calling": caps.tools,
            "supports_reasoning": caps.reasoning,
            "supports_vision": caps.vision,
            "supports_prompt_cache": caps.prompt_cache,
            "timeout_ms": cfg.timeout_ms,
            "device": cfg.runtime.device,
            "kv_cache_precision": cfg.runtime.kv_cache_precision,
            "enable_thinking_default": entry.enable_thinking_default,
            "hot": is_hot,
        },
    }


def build_v1_models_payload(
    cfg: OpenVinoSettings,
    loaded_model_id: str | None = None,
) -> dict[str, Any]:
    created = 1761220000
    return {
        "object": "list",
        "data": [
            build_v1_model_card(m, cfg, loaded_model_id=loaded_model_id, created_ts=created)
            for m in cfg.models
        ],
    }
