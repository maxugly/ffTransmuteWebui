DEFAULT_HOST = "127.0.0.1"
DEFAULT_PORT = 2431
DEFAULT_API_KEY = "openvino-local"
DEFAULT_TIMEOUT_MS = 300000
DEFAULT_MODEL_ID = "Qwen3-8B-int4-ov"
